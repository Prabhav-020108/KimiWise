import React, { useState } from 'react';
import { Mic, MicOff, Send, X, Sparkles, Loader2, Volume2 } from 'lucide-react';
import { useVoice } from '../../hooks/useVoice';
import { AudioVisualizer } from './AudioVisualizer';
import { useStore } from '../../store';
import { aiService } from '../../services/aiService';

declare const fabric: any;

export const VoiceIsland: React.FC = () => {
  const {
    isRecording,
    transcript,
    interimTranscript,
    audioData,
    startRecording,
    stopRecording,
    resetTranscript,
  } = useVoice();

  const {
    agent,
    setAgentState,
    addChatMessage,
    canvas,
    setDomElements,
  } = useStore();

  const [customInput, setCustomInput] = useState<string>('');
  const [isInputExpanded, setIsInputExpanded] = useState<boolean>(false);

  // ── Execute Tool Actions Generated by Gemma 4 ─────────────────────────────
  const executeActionsOnCanvas = (actions: any[]) => {
    const fCanvas = (window as any).__KIMIWISE_CANVAS__;
    const FabricClass = (window as any).fabric;
    if (!fCanvas || !FabricClass) return;

    actions.forEach((action, idx) => {
      const p = action.payload || {};
      const delay = idx * 150;

      setTimeout(() => {
        switch (action.type) {
          case 'CREATE_SHAPE': {
            let shapeObj: any;
            const fill = p.fill || '#6366f1';
            const stroke = p.stroke || '#818cf8';
            const strokeWidth = p.strokeWidth || 2;
            const w = p.width || 180;
            const h = p.height || 100;
            const left = p.x || 200;
            const top = p.y || 200;

            if (p.shape === 'circle') {
              shapeObj = new FabricClass.Circle({
                radius: Math.round(w / 2),
                fill,
                stroke,
                strokeWidth,
                left,
                top,
              });
            } else if (p.shape === 'triangle') {
              shapeObj = new FabricClass.Triangle({
                width: w,
                height: h,
                fill,
                stroke,
                strokeWidth,
                left,
                top,
              });
            } else {
              // Default rectangle
              shapeObj = new FabricClass.Rect({
                width: w,
                height: h,
                rx: 14,
                ry: 14,
                fill,
                stroke,
                strokeWidth,
                left,
                top,
              });
            }

            if (p.label) {
              const textObj = new FabricClass.Text(p.label, {
                fontSize: 16,
                fill: '#ffffff',
                fontFamily: 'Inter, sans-serif',
                fontWeight: 'bold',
                originX: 'center',
                originY: 'center',
                left: left + w / 2,
                top: top + h / 2,
              });
              const group = new FabricClass.Group([shapeObj, textObj], {
                left,
                top,
                id: action.id || `ai_shape_${Date.now()}`,
              });
              fCanvas.add(group);
            } else {
              shapeObj.id = action.id || `ai_shape_${Date.now()}`;
              fCanvas.add(shapeObj);
            }
            break;
          }

          case 'WRITE_TEXT': {
            const textObj = new FabricClass.IText(p.text || '', {
              left: p.x || 200,
              top: p.y || 150,
              fontSize: p.fontSize || 22,
              fill: p.color || '#ffffff',
              fontFamily: 'Inter, sans-serif',
              fontWeight: p.fontWeight || 'bold',
              id: action.id || `ai_text_${Date.now()}`,
            });
            fCanvas.add(textObj);
            break;
          }

          case 'DRAW_ARROW': {
            const fromX = Number(p.fromX) || 100;
            const fromY = Number(p.fromY) || 100;
            const toX = Number(p.toX) || 250;
            const toY = Number(p.toY) || 100;

            const line = new FabricClass.Line([fromX, fromY, toX, toY], {
              stroke: p.color || '#818cf8',
              strokeWidth: p.strokeWidth || 3,
            });

            // Arrow head
            const angle = Math.atan2(toY - fromY, toX - fromX);
            const headLength = 14;
            const head = new FabricClass.Triangle({
              left: toX,
              top: toY,
              originX: 'center',
              originY: 'center',
              pointType: 'arrow_start',
              angle: (angle * 180) / Math.PI + 90,
              width: headLength,
              height: headLength,
              fill: p.color || '#818cf8',
            });

            const arrowGroup = new FabricClass.Group([line, head], {
              id: action.id || `ai_arrow_${Date.now()}`,
            });
            fCanvas.add(arrowGroup);
            break;
          }

          case 'CREATE_MINDMAP': {
            const centralTopic = p.centralTopic || 'Core Concept';
            const branches: { title: string; items?: string[] }[] = p.branches || [];

            const cx = p.centerX || 450;
            const cy = p.centerY || 350;

            // Central bubble
            const centerRect = new FabricClass.Rect({
              width: 200,
              height: 70,
              rx: 18,
              ry: 18,
              fill: '#4f46e5',
              stroke: '#818cf8',
              strokeWidth: 2,
              originX: 'center',
              originY: 'center',
            });
            const centerText = new FabricClass.Text(centralTopic, {
              fontSize: 18,
              fill: '#ffffff',
              fontFamily: 'Inter, sans-serif',
              fontWeight: 'bold',
              originX: 'center',
              originY: 'center',
            });
            const centerGroup = new FabricClass.Group([centerRect, centerText], {
              left: cx,
              top: cy,
              originX: 'center',
              originY: 'center',
            });
            fCanvas.add(centerGroup);

            // Radially place branch bubbles
            branches.forEach((branch, bIdx) => {
              const angle = (bIdx / branches.length) * 2 * Math.PI;
              const radius = 220;
              const bx = cx + Math.cos(angle) * radius;
              const by = cy + Math.sin(angle) * radius;

              // Connecting line
              const line = new FabricClass.Line([cx, cy, bx, by], {
                stroke: '#6366f1',
                strokeWidth: 2,
                opacity: 0.6,
              });
              fCanvas.add(line);
              line.sendToBack();

              // Branch box
              const bRect = new FabricClass.Rect({
                width: 150,
                height: 50,
                rx: 12,
                ry: 12,
                fill: '#1e1b4b',
                stroke: '#6366f1',
                strokeWidth: 1.5,
                originX: 'center',
                originY: 'center',
              });
              const bText = new FabricClass.Text(branch.title, {
                fontSize: 13,
                fill: '#e0e7ff',
                fontFamily: 'Inter, sans-serif',
                originX: 'center',
                originY: 'center',
              });
              const bGroup = new FabricClass.Group([bRect, bText], {
                left: bx,
                top: by,
                originX: 'center',
                originY: 'center',
              });
              fCanvas.add(bGroup);
            });
            break;
          }

          case 'RENDER_HTML': {
            if (p.html) {
              const newDomEl = {
                id: action.id || `dom_${Date.now()}`,
                html: p.html,
                componentType: p.componentType || 'card',
                x: p.x || 300,
                y: p.y || 200,
                width: p.width || 360,
                height: p.height || 220,
                scaleX: 1,
                scaleY: 1,
                rotation: 0,
                zIndex: 10,
              };
              setDomElements({
                ...canvas.domElements,
                [newDomEl.id]: newDomEl,
              });
            }
            break;
          }

          case 'CLEAR_CANVAS': {
            fCanvas.clear();
            fCanvas.backgroundColor = 'transparent';
            break;
          }

          case 'PAN_CAMERA': {
            if (p.x !== undefined && p.y !== undefined) {
              fCanvas.absolutePan(new FabricClass.Point(p.x, p.y));
            }
            break;
          }

          default:
            break;
        }

        fCanvas.requestRenderAll();
      }, delay);
    });
  };

  // ── Dispatch Voice / Prompt to Gemma 4 ─────────────────────────────────────
  const handleSubmitCommand = async (commandText: string) => {
    const textToSend = commandText.trim();
    if (!textToSend || agent.isThinking) return;

    if (isRecording) {
      stopRecording();
    }

    setAgentState({
      isThinking: true,
      isActing: true,
      agentMessage: `Gemma 4 is processing: "${textToSend}"`,
    });

    // Add to chat history
    addChatMessage({
      id: `voice_${Date.now()}`,
      role: 'user',
      text: textToSend,
      timestamp: Date.now(),
    });

    try {
      const response = await aiService.generateBoardActions({
        prompt: textToSend,
        intent: 'creation',
      });

      if (response.textResponse) {
        setAgentState({ agentMessage: response.textResponse });
        addChatMessage({
          id: `ai_${Date.now()}`,
          role: 'model',
          text: response.textResponse,
          timestamp: Date.now(),
          model: response.model || 'Gemma 4',
        });
      }

      if (response.actions && response.actions.length > 0) {
        executeActionsOnCanvas(response.actions);
      }
    } catch (err: any) {
      console.error('[VoiceIsland] Failed to execute voice command:', err);
      setAgentState({ agentMessage: `Failed: ${err?.message || 'Error communicating with AI'}` });
    } finally {
      setAgentState({ isThinking: false, isActing: false });
      resetTranscript();
      setCustomInput('');
      setIsInputExpanded(false);
    }
  };

  const displayText = transcript || interimTranscript || customInput;

  return (
    <div className="absolute bottom-6 left-1/2 -translate-x-1/2 z-30 flex flex-col items-center gap-2 max-w-xl w-[92%] sm:w-auto">
      {/* Floating Dynamic Island Bar */}
      <div className="flex items-center gap-3 px-4 py-2.5 rounded-full bg-card/85 backdrop-blur-2xl border border-border/90 shadow-2xl transition-all duration-300 hover:border-primary/50">
        {/* Mic Toggle Button */}
        <button
          onClick={isRecording ? stopRecording : startRecording}
          disabled={agent.isThinking}
          title={isRecording ? 'Click to stop recording' : 'Click to speak'}
          className={`relative w-11 h-11 rounded-full flex items-center justify-center transition-all ${
            isRecording
              ? 'bg-rose-500 text-white shadow-lg shadow-rose-500/40 animate-pulse'
              : 'bg-primary text-white hover:bg-primary/90 shadow-md shadow-indigo-500/30'
          }`}
        >
          {agent.isThinking ? (
            <Loader2 size={18} className="animate-spin" />
          ) : isRecording ? (
            <MicOff size={18} />
          ) : (
            <Mic size={18} />
          )}
        </button>

        {/* Center Section: Audio Waveform & Status */}
        <div className="flex flex-col justify-center min-w-[140px] sm:min-w-[200px] px-1">
          {isRecording ? (
            <div className="flex items-center gap-2">
              <AudioVisualizer isListening={isRecording} audioData={audioData} width={130} height={24} />
              <span className="text-[11px] font-semibold text-rose-400 animate-pulse">Listening...</span>
            </div>
          ) : agent.isThinking ? (
            <div className="flex items-center gap-2 text-indigo-400 text-xs font-medium">
              <Sparkles size={14} className="animate-spin text-indigo-400" />
              <span>Gemma 4 is creating...</span>
            </div>
          ) : isInputExpanded ? (
            <input
              type="text"
              value={customInput}
              onChange={(e) => setCustomInput(e.target.value)}
              onKeyDown={(e) => e.key === 'Enter' && handleSubmitCommand(customInput)}
              placeholder="Type whiteboard instructions..."
              className="bg-transparent border-none outline-none text-xs text-foreground placeholder:text-muted-foreground w-full"
              autoFocus
            />
          ) : (
            <div
              onClick={() => setIsInputExpanded(true)}
              className="text-xs text-muted-foreground hover:text-foreground cursor-pointer flex items-center gap-1.5 truncate"
            >
              <Volume2 size={14} className="text-primary/70 shrink-0" />
              <span className="truncate">
                {displayText || 'Speak or type a command for the board...'}
              </span>
            </div>
          )}

          {/* Real-time speech transcript subtext */}
          {isRecording && displayText && (
            <span className="text-[10px] text-muted-foreground truncate max-w-[220px]">
              {displayText}
            </span>
          )}
        </div>

        {/* Action Controls */}
        <div className="flex items-center gap-1.5">
          {displayText && !agent.isThinking && (
            <button
              onClick={() => handleSubmitCommand(displayText)}
              className="w-9 h-9 rounded-full bg-primary text-white flex items-center justify-center hover:bg-primary/90 transition-all shadow-sm"
              title="Submit command to board"
            >
              <Send size={14} />
            </button>
          )}

          {(isRecording || displayText || isInputExpanded) && !agent.isThinking && (
            <button
              onClick={() => {
                if (isRecording) stopRecording();
                resetTranscript();
                setCustomInput('');
                setIsInputExpanded(false);
              }}
              className="w-8 h-8 rounded-full hover:bg-muted text-muted-foreground hover:text-foreground flex items-center justify-center transition-all"
              title="Cancel"
            >
              <X size={14} />
            </button>
          )}
        </div>
      </div>

      {/* Suggested Quick Voice Prompts */}
      {!isRecording && !displayText && !agent.isThinking && (
        <div className="hidden sm:flex items-center gap-1.5 text-[11px] text-muted-foreground/80">
          <span>Try:</span>
          {[
            'Draw a mindmap about photosynthesis',
            'Write title: Quantum Computing 101',
            'Draw a flowchart for sorting algorithms',
          ].map((prompt) => (
            <button
              key={prompt}
              onClick={() => handleSubmitCommand(prompt)}
              className="px-2.5 py-1 rounded-full bg-card/60 backdrop-blur-md border border-border/60 hover:border-primary/50 hover:text-foreground transition-all truncate max-w-[200px]"
            >
              {prompt}
            </button>
          ))}
        </div>
      )}
    </div>
  );
};
